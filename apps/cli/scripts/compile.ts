// Builds the `zetta` program as one file: `bun run compile [--target bun-linux-x64]`, into apps/cli/dist. The file needs no clone of
// the repository and no Bun: it carries the pinned versions a server gets and the commit it was built from, which is the code
// `zetta infra deploy` fetches when it runs outside a clone.
import { readVersions } from "@zetta/infra";
import { mkdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dir, "..");
const repository = join(root, "../..");
const at = process.argv.indexOf("--target");
const target = at === -1 ? undefined : process.argv[at + 1];
// `bun-linux-x64-musl` names the platform after its first part.
const platform = target
  ? target.split("-").slice(1).join("-")
  : `${process.platform}-${process.arch}`;

const git = (...args: string[]) => {
  const done = Bun.spawnSync(["git", ...args], { cwd: repository, stderr: "inherit" });
  if (done.exitCode !== 0) process.exit(done.exitCode ?? 1);
  return done.stdout.toString().trim();
};
const commit = git("rev-parse", "HEAD");
if (git("status", "--porcelain") !== "")
  console.warn(
    `warning: there is uncommitted work here. It is compiled in, but outside a clone \`deploy\` fetches commit ${commit.slice(0, 12)}.`,
  );

const work = join(root, ".compile");
mkdirSync(work, { recursive: true });
writeFileSync(
  join(work, "embedded.json"),
  JSON.stringify({ versions: readVersions(repository), commit }),
);
writeFileSync(
  join(work, "entry.ts"),
  `// Generated by scripts/compile.ts.
import carried from "./embedded.json";

(globalThis as { zettaInfraEmbedded?: unknown }).zettaInfraEmbedded = carried;
await import("../src/index.ts");
`,
);

const outfile = join(
  root,
  "dist",
  `zetta-${platform}${platform.startsWith("windows") ? ".exe" : ""}`,
);
// The .env and bunfig.toml of the folder the program is run in are not its own: it reads neither.
const build = Bun.spawnSync(
  [
    process.execPath,
    "build",
    "--compile",
    "--no-compile-autoload-dotenv",
    "--no-compile-autoload-bunfig",
    "--minify",
    "--sourcemap",
    ...(target ? [`--target=${target}`] : []),
    join(work, "entry.ts"),
    "--outfile",
    outfile,
  ],
  { cwd: root, stdout: "inherit", stderr: "inherit" },
);
if (build.exitCode !== 0) process.exit(build.exitCode ?? 1);
console.log(
  `✓ ${relative(process.cwd(), outfile)} (${(statSync(outfile).size / 1024 / 1024).toFixed(1)} MB, commit ${commit.slice(0, 12)})`,
);
