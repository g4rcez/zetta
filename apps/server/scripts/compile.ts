// Builds the single-file server: `bun run compile [--target bun-linux-x64]`. The binary carries the Postgres runtime archive for its
// platform and every migration, so an empty DATABASE_URL needs nothing else on the computer. Build the archive first with
// `bun run db:runtime` (root) on the platform you compile for, or download it from a `pg-runtime-v*` release into packages/db/.pg-runtime.
import { migrationNames } from "@zetta/db/embedded/migrate";
import { archiveName, checkoutMigrations, runtimePlatform } from "@zetta/db/embedded/paths";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dir, "..");
const at = process.argv.indexOf("--target");
const target = at === -1 ? undefined : process.argv[at + 1];
// `bun-linux-x64-musl` and friends name the platform in their second and third parts.
const [, os, arch] = target?.split("-") ?? [];
const platform = target
  ? runtimePlatform(os === "windows" ? "win32" : os, arch)
  : runtimePlatform();

const archive = join(root, "../../packages/db/.pg-runtime", archiveName(platform));
if (!existsSync(archive)) {
  console.error(
    `Missing ${relative(process.cwd(), archive)}: run \`bun run db:runtime\` on ${platform}, or download it from a pg-runtime release.`,
  );
  process.exit(1);
}

const work = join(root, ".compile");
mkdirSync(work, { recursive: true });
const folder = checkoutMigrations();
const migrations = migrationNames(folder).map((name) => ({
  name,
  sql: readFileSync(join(folder, name, "migration.sql"), "utf8"),
}));
writeFileSync(join(work, "migrations.json"), JSON.stringify(migrations));
writeFileSync(
  join(work, "entry.ts"),
  `// Generated by scripts/compile.ts.
import archive from ${JSON.stringify(relative(work, archive))} with { type: "file" };
import migrations from "./migrations.json" with { type: "file" };

(globalThis as { zettaEmbeddedSources?: unknown }).zettaEmbeddedSources = { archive, migrations };
await import("../src/index.ts");
`,
);

const outfile = join(
  root,
  "dist",
  `zetta-server-${platform}${platform.startsWith("win32") ? ".exe" : ""}`,
);
const build = Bun.spawnSync(
  [
    "bun",
    "build",
    "--compile",
    "--no-compile-autoload-dotenv",
    "--minify",
    "--sourcemap",
    ...(target ? [`--target=${target}`] : []),
    join(work, "entry.ts"),
    "--outfile",
    outfile,
  ],
  { cwd: root, stdout: "inherit", stderr: "inherit" },
);
if (build.exitCode !== 0) process.exit(build.exitCode ?? 1);
console.log(
  `✓ ${relative(process.cwd(), outfile)} (${(statSync(outfile).size / 1024 / 1024).toFixed(1)} MB, ${migrations.length} migrations)`,
);
